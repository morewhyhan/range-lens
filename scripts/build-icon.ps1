$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$iconRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../desktop'))
$bitmap = [Drawing.Bitmap]::new(256, 256)
$graphics = [Drawing.Graphics]::FromImage($bitmap)
$graphics.SmoothingMode = [Drawing.Drawing2D.SmoothingMode]::AntiAlias
$graphics.Clear([Drawing.Color]::Transparent)
$graphics.ScaleTransform(4, 4)
$background = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml('#102c28'))
$foreground = [Drawing.SolidBrush]::new([Drawing.ColorTranslator]::FromHtml('#cfef9f'))
$shape = [Drawing.Drawing2D.GraphicsPath]::new()
$shape.AddArc(0,0,32,32,180,90)
$shape.AddArc(32,0,32,32,270,90)
$shape.AddArc(32,32,32,32,0,90)
$shape.AddArc(0,32,32,32,90,90)
$shape.CloseFigure()
$graphics.FillPath($background,$shape)
$spade = [Drawing.Drawing2D.GraphicsPath]::new()
$spade.StartFigure()
$spade.AddBezier(32,12,23,23,12,27,12,37)
$spade.AddBezier(12,37,12,47,22,50,29,44)
$spade.AddLine(29,44,25,53)
$spade.AddLine(25,53,39,53)
$spade.AddLine(39,53,35,44)
$spade.AddBezier(35,44,42,50,52,47,52,37)
$spade.AddBezier(52,37,52,27,41,23,32,12)
$spade.CloseFigure()
$graphics.FillPath($foreground,$spade)
$imageBytes = [IO.MemoryStream]::new()
$bitmap.Save($imageBytes,[Drawing.Imaging.ImageFormat]::Png)
$png = $imageBytes.ToArray()
$stream = [IO.File]::Create((Join-Path $iconRoot 'icon.ico'))
$writer = [IO.BinaryWriter]::new($stream)
$writer.Write([UInt16]0); $writer.Write([UInt16]1); $writer.Write([UInt16]1)
$writer.Write([byte]0); $writer.Write([byte]0); $writer.Write([byte]0); $writer.Write([byte]0)
$writer.Write([UInt16]1); $writer.Write([UInt16]32)
$writer.Write([UInt32]$png.Length); $writer.Write([UInt32]22); $writer.Write($png)
$writer.Dispose(); $stream.Dispose(); $imageBytes.Dispose()
$graphics.Dispose(); $bitmap.Dispose(); $shape.Dispose(); $spade.Dispose()
$background.Dispose(); $foreground.Dispose()
Write-Output 'Generated desktop/icon.ico from the existing spade favicon.'
